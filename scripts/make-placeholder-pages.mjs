const TEMPLATE = (page) => `/**
 * ${page.id} — /${page.route}
 *
 * Generated by scripts/make-placeholder-pages.mjs.
 *
 * Deliberately not a mock-up. See src/components/shell/not-built-yet.tsx for
 * why a fake search box or placeholder article list is worse than an honest
 * empty page on a health platform.
 */

import type { Metadata } from 'next';
import { NotBuiltYet } from '@/components/shell/not-built-yet';

export const metadata: Metadata = {
  title: ${JSON.stringify(page.metaTitle)},
  description: ${JSON.stringify(page.metaDescription)},
  // Not indexed while it has no content: an indexed empty page is a doorway
  // page, and it would rank for queries it cannot answer.
  robots: { index: false, follow: true },
};

export default function Page() {
  return (
    <NotBuiltYet
      title={${JSON.stringify(page.title)}}
      description={${JSON.stringify(page.description)}}
      phase={${JSON.stringify(page.phase)}}
      alternatives={${JSON.stringify(page.alternatives)}}
    />
  );
}
`;

let written = 0;
for (const page of PAGES) {
  const target = resolve(process.cwd(), `src/app/(site)/${page.route}/page.tsx`);
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, TEMPLATE(page), 'utf8');
  written += 1;
  console.log(`  wrote src/app/(site)/${page.route}/page.tsx`);
}

console.log(`\n${written} placeholder pages generated.`);
